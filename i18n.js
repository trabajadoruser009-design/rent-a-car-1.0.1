const languageStorageKey = "aa-rent-a-car-language";
const languageSelects = document.querySelectorAll(".selector-idioma");
const supportedLanguages = Object.keys(translations);
const languagePickerSyncers = [];
const languageOptions = [
  { value: "es", code: "ES", name: "Español" },
  { value: "en", code: "EN", name: "English" },
  { value: "fr", code: "FR", name: "Français" },
];
let currentLanguage = document.documentElement.lang;

function setupLanguagePicker(select) {
  const container = select.closest(".selector-idioma-contenedor");
  const label = container.querySelector(".solo-lectores");
  const button = document.createElement("button");
  const menu = document.createElement("div");
  const menuItems = [];

  button.type = "button";
  button.className = "selector-idioma-boton";
  button.setAttribute("aria-haspopup", "menu");
  button.setAttribute("aria-expanded", "false");
  button.setAttribute("aria-labelledby", label.id);
  button.dataset.i18nAriaLabel = "language_label";
  button.innerHTML = '<span class="selector-idioma-codigo"></span><svg viewBox="0 0 12 8" aria-hidden="true"><path d="m1 1 5 5 5-5"></path></svg>';

  menu.className = "selector-idioma-menu";
  menu.setAttribute("role", "menu");
  menu.setAttribute("aria-labelledby", label.id);
  menu.hidden = true;

  languageOptions.forEach(({ value, code, name }) => {
    const item = document.createElement("button");
    item.type = "button";
    item.className = "selector-idioma-opcion";
    item.setAttribute("role", "menuitemradio");
    item.setAttribute("aria-checked", "false");
    item.tabIndex = -1;
    item.dataset.language = value;
    item.innerHTML = `<span class="selector-idioma-opcion-codigo" aria-hidden="true">${code}</span><span class="selector-idioma-opcion-nombre">${name}</span><svg viewBox="0 0 16 16" aria-hidden="true"><path d="m3 8 3 3 7-7"></path></svg>`;
    menu.append(item);
    menuItems.push(item);

    item.addEventListener("click", () => {
      select.value = value;
      select.dispatchEvent(new Event("change", { bubbles: true }));
      closeMenu(true);
    });
  });

  container.append(button, menu);

  function syncSelection(language) {
    const selectedOption = languageOptions.find((option) => option.value === language);
    button.querySelector(".selector-idioma-codigo").textContent = selectedOption.code;
    menuItems.forEach((item) => {
      const isSelected = item.dataset.language === language;
      item.setAttribute("aria-checked", String(isSelected));
      item.classList.toggle("is-seleccionado", isSelected);
    });
  }

  function closeMenu(returnFocus = false) {
    if (menu.hidden) return;
    menu.hidden = true;
    button.setAttribute("aria-expanded", "false");
    container.classList.remove("is-abierto");
    if (returnFocus) button.focus();
  }

  function openMenu(index) {
    menu.hidden = false;
    button.setAttribute("aria-expanded", "true");
    container.classList.add("is-abierto");
    menuItems[index].focus();
  }

  button.addEventListener("click", () => {
    if (menu.hidden) {
      const selectedIndex = menuItems.findIndex((item) => item.dataset.language === select.value);
      openMenu(Math.max(0, selectedIndex));
    } else {
      closeMenu();
    }
  });

  button.addEventListener("keydown", (event) => {
    if (event.key === "ArrowDown") {
      event.preventDefault();
      const selectedIndex = menuItems.findIndex((item) => item.dataset.language === select.value);
      openMenu(Math.max(0, selectedIndex));
    } else if (event.key === "ArrowUp") {
      event.preventDefault();
      openMenu(menuItems.length - 1);
    }
  });

  menu.addEventListener("keydown", (event) => {
    const activeIndex = menuItems.indexOf(document.activeElement);
    if (event.key === "Escape") {
      event.preventDefault();
      closeMenu(true);
    } else if (event.key === "ArrowDown" || event.key === "ArrowUp" || event.key === "Home" || event.key === "End") {
      event.preventDefault();
      let nextIndex = activeIndex;
      if (event.key === "ArrowDown") nextIndex = (activeIndex + 1) % menuItems.length;
      if (event.key === "ArrowUp") nextIndex = (activeIndex - 1 + menuItems.length) % menuItems.length;
      if (event.key === "Home") nextIndex = 0;
      if (event.key === "End") nextIndex = menuItems.length - 1;
      menuItems[nextIndex].focus();
    }
    if (event.key === "Tab") window.setTimeout(() => closeMenu(), 0);
  });

  document.addEventListener("pointerdown", (event) => {
    if (!container.contains(event.target)) closeMenu();
  });
  document.addEventListener("focusin", (event) => {
    if (!container.contains(event.target)) closeMenu();
  });

  languagePickerSyncers.push(syncSelection);
  syncSelection(select.value);
}

languageSelects.forEach(setupLanguagePicker);

function getSavedLanguage() {
  try {
    const savedLanguage = localStorage.getItem(languageStorageKey);
    return supportedLanguages.includes(savedLanguage) ? savedLanguage : "es";
  } catch (error) {
    console.warn("No se pudo leer el idioma guardado; se usará español.", error);
    return "es";
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem(languageStorageKey, language);
  } catch (error) {
    console.warn("No se pudo guardar el idioma seleccionado.", error);
  }
}

function translatePage(language) {
  const dictionary = translations[language];
  if (!dictionary) throw new Error(`Idioma no compatible: ${language}`);

  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation !== undefined) element.textContent = translation;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nAriaLabel];
    if (translation !== undefined) element.setAttribute("aria-label", translation);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nAlt];
    if (translation !== undefined) element.alt = translation;
  });
  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nContent];
    if (translation !== undefined) element.setAttribute("content", translation);
  });

  const translatedTitle = document.querySelector("title[data-i18n]");
  if (translatedTitle) document.title = dictionary[translatedTitle.dataset.i18n] || document.title;
  languageSelects.forEach((select) => {
    select.value = language;
  });
  languagePickerSyncers.forEach((syncSelection) => syncSelection(language));
  document.dispatchEvent(new CustomEvent("aa-language-change", { detail: { language } }));
}

languageSelects.forEach((select) => {
  select.addEventListener("change", () => {
    if (!supportedLanguages.includes(select.value)) {
      throw new Error(`Idioma seleccionado no compatible: ${select.value}`);
    }
    saveLanguage(select.value);
    translatePage(select.value);
  });
});

window.AARentCarI18n = {
  get language() {
    return currentLanguage;
  },
  translatePage,
  t(key) {
    const translation = translations[currentLanguage][key];
    if (translation === undefined) throw new Error(`Falta la traducción "${key}" para ${currentLanguage}.`);
    return translation;
  },
};

translatePage(getSavedLanguage());
